// Determine Python type
function getPyType(
  value: unknown,
  models: Record<string, string>,
  nameHint: string,
  imports: Set<string>
): string {
  if (value === null) {
    imports.add('Optional');
    imports.add('Any');
    return 'Optional[Any]';
  }

  if (Array.isArray(value)) {
    imports.add('List');
    if (value.length === 0) {
      imports.add('Any');
      return 'List[Any]';
    }
    // Get unique item types
    const types = Array.from(
      new Set(value.map((v) => getPyType(v, models, nameHint + 'Item', imports)))
    );
    if (types.length === 1) return `List[${types[0]}]`;
    imports.add('Union');
    return `List[Union[${types.join(', ')}]]`;
  }

  if (typeof value === 'object' && value !== null) {
    const className = capitalize(nameHint);
    // Build the model
    const lines: string[] = [];
    for (const [k, v] of Object.entries(value)) {
      lines.push(`    ${k}: ${getPyType(v, models, k, imports)}`);
    }
    models[className] = `class ${className}(BaseModel):\n${lines.join('\n')}`;
    return className;
  }

  if (typeof value === 'number') return Number.isInteger(value) ? 'int' : 'float';
  if (typeof value === 'boolean') return 'bool';
  if (typeof value === 'string') return 'str';
  return 'Any';
}

function capitalize(str: string): string {
  return str.charAt(0).toUpperCase() + str.slice(1);
}

function generatePydantic(json: Record<string, unknown> | unknown[]): string {
  const models: Record<string, string> = {};
  const imports = new Set<string>(['BaseModel']);

  let mainCode = '';

  if (Array.isArray(json)) {
    if (json.length === 0) {
      imports.add('List');
      imports.add('Any');
      mainCode = `class AutoGenerated(BaseModel):\n    items: List[Any]`;
    } else {
      imports.add('List');
      const itemType = getPyType(json[0], models, 'AutoGeneratedItem', imports);
      mainCode = `class AutoGenerated(BaseModel):\n    items: List[${itemType}]`;
    }
  } else if (typeof json === 'object' && json !== null) {
    const lines: string[] = [];
    for (const [k, v] of Object.entries(json)) {
      lines.push(`    ${k}: ${getPyType(v, models, k, imports)}`);
    }
    mainCode = `class AutoGenerated(BaseModel):\n${lines.join('\n')}`;
  } else {
    imports.add('Any');
    mainCode = `class AutoGenerated(BaseModel):\n    value: Any`;
  }

  // Build import lines
  const importLines: string[] = [];
  importLines.push(`from pydantic import BaseModel`);

  const typingImports = Array.from(imports)
    .filter((i) => i !== 'BaseModel')
    .sort();
  if (typingImports.length > 0) {
    importLines.push(`from typing import ${typingImports.join(', ')}`);
  }

  // Combine: imports, then nested models, then main model
  const modelBlocks = Object.values(models);
  const allBlocks = [...modelBlocks, mainCode];

  return importLines.join('\n') + '\n\n\n' + allBlocks.join('\n\n\n');
}

