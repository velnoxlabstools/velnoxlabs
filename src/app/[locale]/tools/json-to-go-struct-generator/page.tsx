// Convert key to Go field name (PascalCase)
function toGoFieldName(key: string): string {
  const parts = key.split(/[_\-\s.]+/).filter(Boolean);
  if (parts.length === 0) return 'Field';
  return parts.map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
}

// Singularize for array item struct names
function singularize(word: string): string {
  if (word.endsWith('ies')) return word.slice(0, -3) + 'y';
  if (/(ses|xes|zes|ches|shes)$/.test(word)) return word.slice(0, -2);
  if (word.endsWith('s') && !word.endsWith('ss')) return word.slice(0, -1);
  return word;
}

function toGoStructName(nameHint: string): string {
  const parts = nameHint.split(/[_\-\s.]+/).filter(Boolean);
  if (parts.length === 0) return 'Generated';
  return parts.map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
}

// Determine Go type
function getGoType(value: unknown, structs: Record<string, string>, nameHint: string): string {
  if (value === null) return 'interface{}';

  if (Array.isArray(value)) {
    if (value.length === 0) return '[]interface{}';
    const itemNameHint = singularize(nameHint);
    const types = Array.from(new Set(value.map((v) => getGoType(v, structs, itemNameHint))));
    if (types.length === 1) return `[]${types[0]}`;
    return '[]interface{}';
  }

  if (typeof value === 'object' && value !== null) {
    const structName = toGoStructName(nameHint);
    const fields: string[] = [];
    for (const [k, v] of Object.entries(value)) {
      const fieldName = toGoFieldName(k);
      const fieldType = getGoType(v, structs, k);
      fields.push(`\t${fieldName} ${fieldType} \`json:"${k}"\``);
    }
    structs[structName] = `type ${structName} struct {\n${fields.join('\n')}\n}`;
    return structName;
  }

  if (typeof value === 'number') return Number.isInteger(value) ? 'int' : 'float64';
  if (typeof value === 'boolean') return 'bool';
  if (typeof value === 'string') return 'string';
  return 'interface{}';
}

function generateGoStruct(json: Record<string, unknown> | unknown[]): string {
  const structs: Record<string, string> = {};

  if (Array.isArray(json)) {
    if (json.length === 0) {
      return 'type AutoGenerated = []interface{}';
    }
    const itemType = getGoType(json[0], structs, 'AutoGeneratedItem');
    const structBlocks = Object.values(structs);
    return [...structBlocks, `type AutoGenerated = []${itemType}`].join('\n\n');
  }

  if (typeof json === 'object' && json !== null) {
    const fields: string[] = [];
    for (const [k, v] of Object.entries(json)) {
      const fieldName = toGoFieldName(k);
      const fieldType = getGoType(v, structs, k);
      fields.push(`\t${fieldName} ${fieldType} \`json:"${k}"\``);
    }
    const mainStruct = `type AutoGenerated struct {\n${fields.join('\n')}\n}`;
    const structBlocks = Object.values(structs);
    return [...structBlocks, mainStruct].join('\n\n');
  }

  return `type AutoGenerated = ${getGoType(json, structs, 'AutoGenerated')}`;
}

